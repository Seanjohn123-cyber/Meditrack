"""
VCD Waveform to Image Screenshot Generator
Parses standard Value Change Dump (.vcd) files generated by Icarus Verilog
and renders GTKWave-style digital timing diagrams as high-resolution PNG images.
"""

import sys
import os
import re
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np

def parse_vcd(vcd_path):
    signals = {}       # id -> {'name': name, 'type': type, 'size': size}
    name_to_id = {}    # name -> id
    timescale = 1e-9   # default 1ns
    
    with open(vcd_path, 'r') as f:
        lines = f.readlines()
        
    in_header = True
    scope = []
    changes = {} # id -> list of (time, val_str)
    curr_time = 0
    
    for line in lines:
        line = line.strip()
        if not line:
            continue
            
        if in_header:
            if line.startswith('$timescale'):
                # rough parse
                pass
            elif line.startswith('$scope'):
                parts = line.split()
                if len(parts) >= 3:
                    scope.append(parts[2])
            elif line.startswith('$upscope'):
                if scope:
                    scope.pop()
            elif line.startswith('$var'):
                parts = line.split()
                # $var wire 1 ! clk $end
                # $var reg 4 " active_slot [3:0] $end
                if len(parts) >= 5:
                    var_type = parts[1]
                    var_size = int(parts[2])
                    var_id = parts[3]
                    var_name = parts[4]
                    full_name = ".".join(scope + [var_name]) if scope else var_name
                    signals[var_id] = {
                        'name': full_name,
                        'short_name': var_name,
                        'type': var_type,
                        'size': var_size
                    }
                    name_to_id[full_name] = var_id
                    changes[var_id] = []
            elif line.startswith('$enddefinitions'):
                in_header = False
        else:
            if line.startswith('#'):
                curr_time = int(line[1:])
            elif line.startswith('$'):
                continue
            else:
                # Value change
                # Single bit: 0!, 1!, x!, z!
                # Multi bit: b0010 ", b1010 "
                if line.startswith('b') or line.startswith('B'):
                    parts = line.split()
                    val = parts[0][1:]
                    var_id = parts[1]
                    if var_id in changes:
                        changes[var_id].append((curr_time, val))
                else:
                    val = line[0]
                    var_id = line[1:]
                    if var_id in changes:
                        changes[var_id].append((curr_time, val))
                        
    return signals, changes

def render_waveforms(vcd_path, output_png_path, signal_filter=None, time_window=None, title=None):
    signals, changes = parse_vcd(vcd_path)
    if not signals:
        print(f"No signals found in {vcd_path}")
        return

    # Select signals to plot
    selected_ids = []
    if signal_filter:
        for s_id, s_info in signals.items():
            name = s_info['short_name']
            full = s_info['name']
            if any(f in name or f in full for f in signal_filter):
                selected_ids.append(s_id)
    else:
        # Sort by hierarchy depth then name
        selected_ids = list(signals.keys())[:14] # at most 14 for visibility

    if not selected_ids:
        selected_ids = list(signals.keys())[:10]

    # Find time range
    all_times = [0]
    for s_id in selected_ids:
        for t, _ in changes[s_id]:
            all_times.append(t)
    max_time = max(all_times) if all_times else 100
    if time_window:
        t_start, t_end = time_window
    else:
        t_start, t_end = 0, max_time

    num_signals = len(selected_ids)
    fig_height = max(5, 0.65 * num_signals + 1.8)
    fig, ax = plt.subplots(figsize=(15, fig_height), facecolor='#111827')
    ax.set_facecolor('#111827')

    colors = ['#10B981', '#38BDF8', '#F59E0B', '#EC4899', '#A855F7', '#34D399', '#F87171']

    y_positions = []
    y_labels = []

    for idx, s_id in enumerate(reversed(selected_ids)):
        s_info = signals[s_id]
        name = s_info['short_name']
        is_bus = s_info['size'] > 1
        ch_list = changes[s_id]
        y_base = idx * 1.5
        y_positions.append(y_base + 0.4)
        y_labels.append(name)
        color = colors[idx % len(colors)]

        # Sample at fine intervals
        t_grid = np.linspace(t_start, t_end, 1500)
        # Reconstruct waveform values
        # Sorted transitions
        sorted_ch = sorted(ch_list, key=lambda x: x[0])
        
        # Build piecewise constant curve
        curve_t = [t_start]
        curve_v = []
        
        # Initial value before first transition
        init_val = '0'
        for t, v in sorted_ch:
            if t <= t_start:
                init_val = v
            else:
                break
                
        curr_v = init_val
        last_t = t_start

        plot_t = [t_start]
        plot_y = []

        if not is_bus:
            # Single bit logic (0 or 1)
            def val_to_num(val_str):
                return 1.0 if val_str == '1' else 0.0

            curr_num = val_to_num(init_val)
            t_pts = [t_start]
            y_pts = [y_base + curr_num * 0.8]

            for t, v in sorted_ch:
                if t < t_start or t > t_end:
                    continue
                next_num = val_to_num(v)
                t_pts.append(t)
                y_pts.append(y_base + curr_num * 0.8) # hold previous
                t_pts.append(t)
                y_pts.append(y_base + next_num * 0.8) # step to new
                curr_num = next_num

            t_pts.append(t_end)
            y_pts.append(y_base + curr_num * 0.8)

            ax.step(t_pts, y_pts, where='post', color=color, linewidth=2.0)
            ax.fill_between(t_pts, y_base, y_pts, step='post', color=color, alpha=0.15)
        else:
            # Bus logic (draw cross hatched / envelope with values)
            t_events = [t_start]
            vals = [init_val]
            for t, v in sorted_ch:
                if t < t_start or t > t_end:
                    continue
                t_events.append(t)
                vals.append(v)
            t_events.append(t_end)
            vals.append(vals[-1])

            for k in range(len(t_events) - 1):
                t1 = t_events[k]
                t2 = t_events[k+1]
                v_str = vals[k]
                
                # Draw bus envelope
                ax.plot([t1, t2], [y_base + 0.8, y_base + 0.8], color=color, linewidth=1.5)
                ax.plot([t1, t2], [y_base, y_base], color=color, linewidth=1.5)
                # transitions
                ax.plot([t1, t1], [y_base, y_base + 0.8], color=color, linewidth=1.5)
                ax.plot([t2, t2], [y_base, y_base + 0.8], color=color, linewidth=1.5)
                ax.fill_between([t1, t2], y_base, y_base + 0.8, color=color, alpha=0.12)

                # Text annotation
                if (t2 - t1) > (t_end - t_start) * 0.03:
                    mid = (t1 + t2) / 2
                    try:
                        dec_val = int(v_str, 2)
                        display_text = f"h'{dec_val:X}"
                    except:
                        display_text = v_str
                    ax.text(mid, y_base + 0.4, display_text, color='#F3F4F6',
                            fontsize=8, ha='center', va='center', weight='bold')

    ax.set_yticks(y_positions)
    ax.set_yticklabels(y_labels, color='#F3F4F6', fontsize=10, family='monospace', weight='bold')
    ax.set_xlim(t_start, t_end)
    ax.set_ylim(-0.5, len(selected_ids) * 1.5)
    ax.set_xlabel("Time (ns)", color='#9CA3AF', fontsize=11, labelpad=8)
    ax.tick_params(axis='x', colors='#9CA3AF', labelsize=9)
    ax.grid(True, which='both', axis='x', color='#374151', linestyle='--', alpha=0.7)

    plot_title = title if title else f"Waveform Simulation: {os.path.basename(vcd_path)}"
    ax.set_title(plot_title, color='#F9FAFB', fontsize=14, weight='bold', pad=15)

    for spine in ax.spines.values():
        spine.set_color('#374151')

    plt.tight_layout()
    os.makedirs(os.path.dirname(os.path.abspath(output_png_path)), exist_ok=True)
    plt.savefig(output_png_path, dpi=200, bbox_inches='tight', facecolor='#111827')
    plt.close()
    print(f"Saved waveform screenshot: {output_png_path}")

if __name__ == '__main__':
    if len(sys.argv) < 3:
        print("Usage: python vcd_to_png.py <input.vcd> <output.png> [title]")
        sys.exit(1)
    vcd = sys.argv[1]
    out = sys.argv[2]
    title = sys.argv[3] if len(sys.argv) > 3 else None
    render_waveforms(vcd, out, title=title)
